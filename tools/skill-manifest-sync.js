#!/usr/bin/env node
'use strict';

/**
 * Skill Manifest Generator & Sync Tool
 * ------------------------------------
 * Inspired by Hugging Face Skills (`huggingface/skills` publish.sh / marketplace generator).
 *
 * Scans `.agents/skills/` and `~/.gemini/config/skills/`, parses YAML frontmatters,
 * and synchronizes multi-agent skill registry manifests across:
 *   1. `SKILLS.md` (Canonical Markdown Table)
 *   2. `gemini-extension.json` (Gemini CLI extension config)
 *   3. `.cursor-plugin/plugin.json` (Cursor IDE plugin config)
 *
 * Usage:
 *   node tools/skill-manifest-sync.js          # Sync manifests and print summary
 *   node tools/skill-manifest-sync.js --check  # Validate manifests in CI without writing
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const LOCAL_SKILLS_DIR = path.join(REPO_ROOT, '.agents/skills');
const GLOBAL_SKILLS_DIR = path.join(process.env.HOME || '/Users/igorganapolsky', '.gemini/config/skills');
const SKILLS_MD = path.join(REPO_ROOT, 'SKILLS.md');
const GEMINI_EXT_JSON = path.join(REPO_ROOT, 'gemini-extension.json');
const CURSOR_PLUGIN_JSON = path.join(REPO_ROOT, '.cursor-plugin/plugin.json');

const CHECK_ONLY = process.argv.includes('--check');

/**
 * Simple YAML frontmatter parser for skill header blocks.
 */
function parseFrontmatter(content) {
  if (!content.startsWith('---')) return null;
  const endIdx = content.indexOf('---', 3);
  if (endIdx === -1) return null;

  const header = content.substring(3, endIdx);
  const nameMatch = /^name:\s*(.+)$/m.exec(header);
  const descMatch = /^description:\s*([\s\S]+?)(?=\n[a-z0-9_-]+:|\n---|$)/im.exec(header);

  if (!nameMatch || !descMatch) return null;

  let cleanDesc = descMatch[1]
    .replace(/^(\|-|>|-|>-\s*)/, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^['"]|['"]$/g, '');

  if (!cleanDesc || cleanDesc === '|-' || cleanDesc === '>') {
    cleanDesc = 'Skill instructions and usage guide.';
  }

  return {
    name: nameMatch[1].trim().replace(/^['"]|['"]$/g, ''),
    description: cleanDesc
  };
}

/**
 * Scans a skill directory for valid SKILL.md files.
 */
function scanSkillDirectory(dirPath, sourceName) {
  const results = [];
  if (!fs.existsSync(dirPath)) return results;

  const entries = fs.readdirSync(dirPath, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.isDirectory()) {
      const skillMdPath = path.join(dirPath, entry.name, 'SKILL.md');
      if (fs.existsSync(skillMdPath)) {
        const content = fs.readFileSync(skillMdPath, 'utf8');
        const meta = parseFrontmatter(content);
        const lineCount = content.split('\n').length;

        if (meta) {
          results.push({
            name: meta.name || entry.name,
            folder: entry.name,
            description: meta.description,
            lineCount,
            source: sourceName,
            path: skillMdPath,
            valid: lineCount < 500
          });
        }
      }
    }
  }
  return results;
}

/**
 * Generates canonical SKILLS.md markdown content.
 */
function generateSkillsMd(skills) {
  let md = `# SKILLS.md — Canonical Agent Skill Registry\n\n`;
  md += `Inspired by Hugging Face Skills (\`huggingface/skills\`). Automatically generated by \`tools/skill-manifest-sync.js\`.\n\n`;
  md += `| Skill | Description | Definition | Source |\n`;
  md += `| :--- | :--- | :--- | :--- |\n`;

  for (const skill of skills) {
    const relPath = skill.path.startsWith(process.env.HOME || '/Users/igorganapolsky')
      ? '~' + skill.path.slice((process.env.HOME || '/Users/igorganapolsky').length)
      : path.relative(REPO_ROOT, skill.path);
    md += `| \`${skill.name}\` | ${skill.description} | \`${relPath}\` | ${skill.source} |\n`;
  }

  md += `\n---\n\n*Last synchronized: ${new Date().toISOString()}*\n`;
  return md;
}

/**
 * Main execution function.
 */
function main() {
  const localSkills = scanSkillDirectory(LOCAL_SKILLS_DIR, 'local');
  const globalSkills = scanSkillDirectory(GLOBAL_SKILLS_DIR, 'global');
  const allSkills = [...localSkills, ...globalSkills];

  console.log(`Found ${allSkills.length} total skill packages (${localSkills.length} local, ${globalSkills.length} global).`);

  let invalidCount = 0;
  for (const skill of allSkills) {
    if (!skill.valid) {
      console.warn(`[WARN] Skill '${skill.name}' exceeds 500 line limit (${skill.lineCount} lines)!`);
      invalidCount++;
    }
  }

  const newSkillsMd = generateSkillsMd(allSkills);

  const geminiManifest = {
    name: 'mac-yolo-safeguards-skills',
    description: 'Hugging Face pattern skill extension for Gemini CLI & AGY agents',
    version: '1.0.0',
    skills: allSkills.map(s => ({
      name: s.name,
      description: s.description,
      path: path.relative(REPO_ROOT, s.path)
    }))
  };

  const cursorManifest = {
    name: 'mac-yolo-safeguards-skills',
    description: 'Cursor plugin skill registry',
    version: '1.0.0',
    skills: allSkills.map(s => ({
      name: s.name,
      description: s.description,
      path: path.relative(REPO_ROOT, s.path)
    }))
  };

  if (CHECK_ONLY) {
    const existingMd = fs.existsSync(SKILLS_MD) ? fs.readFileSync(SKILLS_MD, 'utf8') : '';
    const cleanExisting = existingMd.replace(/\*Last synchronized:.*\*/, '').trim();
    const cleanNew = newSkillsMd.replace(/\*Last synchronized:.*\*/, '').trim();

    if (cleanExisting !== cleanNew) {
      console.error('[FAIL] SKILLS.md is out of sync! Run node tools/skill-manifest-sync.js to update.');
      process.exit(1);
    }
    console.log('[PASS] SKILLS.md is up to date.');
    process.exit(0);
  }

  // Write manifests
  fs.writeFileSync(SKILLS_MD, newSkillsMd, 'utf8');
  fs.writeFileSync(GEMINI_EXT_JSON, JSON.stringify(geminiManifest, null, 2) + '\n', 'utf8');

  const cursorDir = path.dirname(CURSOR_PLUGIN_JSON);
  if (!fs.existsSync(cursorDir)) {
    fs.mkdirSync(cursorDir, { recursive: true });
  }
  fs.writeFileSync(CURSOR_PLUGIN_JSON, JSON.stringify(cursorManifest, null, 2) + '\n', 'utf8');

  console.log(`[SUCCESS] Synchronized manifests:`);
  console.log(`  - SKILLS.md (${allSkills.length} entries)`);
  console.log(`  - gemini-extension.json`);
  console.log(`  - .cursor-plugin/plugin.json`);

  if (invalidCount > 0 && process.argv.includes('--strict')) {
    process.exit(1);
  }
  process.exit(0);
}

if (require.main === module) {
  main();
}

module.exports = { parseFrontmatter, scanSkillDirectory, generateSkillsMd };
