#!/usr/bin/env node
'use strict';

/**
 * Apply high-ROI inference routing (write env file + print verification).
 * Does NOT auto-mutate production LiteLLM without --print-only.
 *
 *   node tools/inference-eng/apply-high-roi.js
 *   node tools/inference-eng/apply-high-roi.js --write
 *   node tools/inference-eng/apply-high-roi.js --smoke
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const { selectModelChain } = require('./degradation');
const { selectRoute } = require('../hermes-yolo-route-policy');

const OUT = path.join(os.homedir(), '.hermes', 'inference-eng', 'high-roi-route.env');

const ENV_BLOCK = `# Generated by tools/inference-eng/apply-high-roi.js — 2026-08-13
# Source: source ~/.hermes/inference-eng/high-roi-route.env
# Quality lock: hermes/glm-coding primary (anti deepseek-v4-flash gibberish).
# SuperGrok is opt-in only (HERMES_YOLO_BACKEND=grok or HERMES_PREFER_SUPERGROK=1).

export HERMES_PREFER_SUPERGROK=0
export HERMES_YOLO_BACKEND=hermes
export HERMES_DROP_DEAD_GLM=0
export HERMES_ALLOW_GLM=1
export HERMES_YOLO_MODEL=glm-coding
export HERMES_YOLO_PROVIDER=custom:litellm-gateway
export HERMES_YOLO_ALLOW_FREE_PRIMARY=0
# SuperGrok opt-in:
# export HERMES_PREFER_SUPERGROK=1
# export HERMES_YOLO_BACKEND=grok
`;

function smoke() {
  const cases = [
    { task: 'implement login validation', expect: 'grok-4.5' },
    { task: 'are you sure about this architecture?', expect: 'grok-4.5' },
    { task: 'smoke ping hermes-yolo-ready', expect: 'kimi-code-fast' },
    { task: 'draft outreach email for a founder', expect: 'glm-coding' },
    { task: 'classify this lead spam or buyer', expect: 'glm-coding' },
  ];
  const env = {
    HERMES_PREFER_SUPERGROK: '1',
    HERMES_YOLO_BACKEND: 'auto',
    HERMES_DROP_DEAD_GLM: '0',
  };
  // clear pin pollution
  delete env.HERMES_YOLO_MODEL;
  const results = [];
  for (const c of cases) {
    const r = selectRoute({ task: c.task, env: { ...process.env, ...env, HERMES_YOLO_MODEL: undefined } });
    // force clean env without shell pollution
    const clean = {
      HERMES_PREFER_SUPERGROK: '1',
      HERMES_YOLO_BACKEND: 'auto',
      HERMES_DROP_DEAD_GLM: '0',
    };
    const route = selectRoute({ task: c.task, env: clean });
    const chain = selectModelChain({ taskText: c.task, mode: 'normal', env: clean });
    let ok = true;
    if (c.expect) ok = route.model === c.expect;
    if (c.expectPrimaryStarts) ok = String(route.model).startsWith(c.expectPrimaryStarts);
    results.push({
      task: c.task,
      model: route.model,
      primary: chain.primary,
      ok,
      reason: route.reason,
    });
  }
  return results;
}

function main() {
  const write = process.argv.includes('--write');
  const doSmoke = process.argv.includes('--smoke') || !process.argv.includes('--print-only');
  if (write) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, ENV_BLOCK, { mode: 0o600 });
    console.log(`wrote ${OUT}`);
  } else {
    console.log('--- env block (pass --write to install) ---');
    process.stdout.write(ENV_BLOCK);
  }
  if (doSmoke) {
    console.log('--- smoke routes (clean env) ---');
    const rows = smoke();
    for (const r of rows) {
      console.log(`${r.ok ? 'PASS' : 'FAIL'}  ${r.model.padEnd(22)}  ${r.task}`);
    }
    const failed = rows.filter((r) => !r.ok);
    if (failed.length) {
      console.error(`smoke failed: ${failed.length}`);
      process.exit(1);
    }
    console.log('smoke: ALL PASS');
  }
}

main();
